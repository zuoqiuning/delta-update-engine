pub mod state;

/// Compile-time pinned keys. Public so the `pinned-keys` contract test can
/// exercise it; not part of the supported API.
#[doc(hidden)]
pub mod pinned;

/// Set once [`run_applier_from_context`] has run, whatever the mode.
///
/// The plugin can only see its own `setup`; it cannot see whether the host
/// called the wrapper or plain `.run(context)`. Without this flag a host that
/// forgot the wrapper starts normally and then silently never applies an update,
/// because the restart-to-apply process is a worker this binary never handles.
static ENTRY_USED: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);

pub(crate) fn entry_used() -> bool {
    ENTRY_USED.load(std::sync::atomic::Ordering::Relaxed)
}

pub use config::Config;
pub use delta_update_engine::apply::{
    run_applier, run_applier_from_args, run_applier_from_args_with_keys,
};
pub use events::STATE_EVENT;

/// Handle worker mode with the signed-manifest binding enabled.
///
/// Call this **before** `tauri::Builder::run`, passing the context generated by
/// `tauri::generate_context!()`:
///
/// ```ignore
/// let context = tauri::generate_context!();
/// if let Some(code) = tauri_plugin_delta_update::run_applier_from_context(&context) {
///     std::process::exit(code);
/// }
/// tauri::Builder::default()
///     .plugin(tauri_plugin_delta_update::init())
///     .run(context)
/// ```
///
/// Keys are read from the embedded plugin config, so the worker verifies the
/// signed manifest without trusting `apply.json` or a writable key file.
///
/// Returns `None` for a normal application start. In worker mode an embedded
/// config without keys is rejected instead of silently falling back to
/// unverified journal replay.
pub fn run_applier_from_context<R: Runtime>(context: &tauri::Context<R>) -> Option<i32> {
    ENTRY_USED.store(true, std::sync::atomic::Ordering::Relaxed);
    if !crate::lifecycle::worker_mode_requested(std::env::args_os().skip(1)) {
        return None;
    }
    let keys = context
        .config()
        .plugins
        .0
        .get("delta-update")
        .and_then(|value| value.get("signing_public_keys"))
        .and_then(|value| serde_json::from_value::<Vec<String>>(value.clone()).ok())
        .unwrap_or_default();
    if keys.is_empty() {
        eprintln!(
            "delta update worker: embedded config has no signing_public_keys; refusing to run unverified"
        );
        return Some(1);
    }
    let keys = match crate::pinned::effective_keys(&keys) {
        Ok(keys) => keys,
        Err(error) => {
            eprintln!("delta update worker: {error}; refusing to run with an unpinned trust root");
            return Some(1);
        }
    };
    run_applier_from_args_with_keys(&keys)
}

/// One-line integration: handles worker mode, then starts the GUI.
///
/// ```ignore
/// tauri::Builder::default()
///     .plugin(tauri_plugin_delta_update::init())
///     .run_with_delta_update(tauri::generate_context!())
/// ```
///
/// Replacing `.run(context)` with this method removes the ordering trap: if the
/// process was started as a replacement/recovery worker, it is handled before
/// any GUI is created. [`run_applier_from_context`] stays available for hosts
/// that need a custom startup sequence.
pub trait BuilderExt<R: Runtime> {
    fn run_with_delta_update(self, context: tauri::Context<R>) -> tauri::Result<()>;
}

impl<R: Runtime> BuilderExt<R> for tauri::Builder<R> {
    fn run_with_delta_update(self, context: tauri::Context<R>) -> tauri::Result<()> {
        if let Some(code) = run_applier_from_context(&context) {
            std::process::exit(code);
        }
        self.run(context)
    }
}

pub fn init<R: Runtime>() -> TauriPlugin<R, Config> {
    Builder::<R, Config>::new("delta-update")
        .invoke_handler(tauri::generate_handler![
            commands::check,
            commands::prepare,
            commands::cancel_prepare,
            commands::status,
            commands::confirm_healthy,
            commands::restart_to_apply,
            commands::export_diagnostics,
            commands::open_diagnostics_folder,
            commands::get_update_history,
            commands::clear_skipped_version,
        ])
        .setup(|app, api| {
            lifecycle::setup(app, api.config())?;
            Ok(())
        })
        .on_window_ready(|window| lifecycle::on_window_ready(&window))
        .on_event(|app, event| {
            if matches!(event, RunEvent::Exit) {
                lifecycle::on_exit(app);
            }
        })
        .build()
}
