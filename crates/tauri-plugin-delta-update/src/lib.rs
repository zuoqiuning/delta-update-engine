//! Tauri 2 adapter for the delta update engine.

// One unsafe call site is allowed in `applier` for ShellExecuteW("runas");
// everything else stays safe Rust.
#![deny(unsafe_code)]

#[cfg(not(windows))]
compile_error!(
    "tauri-plugin-delta-update supports Windows desktop only; macOS, Linux and mobile are out of scope and use their platform installer instead"
);

use tauri::plugin::{Builder, TauriPlugin};
use tauri::{RunEvent, Runtime};

